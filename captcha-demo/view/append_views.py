lines.append("                self.canvas.create_polygon(cx, cy-20, cx-20, cy+20, cx+20, cy+20, fill='white', outline='#333', width=2)")
lines.append("    def _on_click(self, event):")
lines.append("        data = self.vm.model.difference_click_data")
lines.append("        if data is None or self.vm.get_state() != CaptchaState.IDLE:")
lines.append("            return")
lines.append("        cols = 3")
lines.append("        size = 80")
lines.append("        pad = 10")
lines.append("        start_x = (self.width - cols * (size + pad)) // 2")
lines.append("        start_y = 20")
lines.append("        for i in range(len(data.images)):")
lines.append("            row, col = divmod(i, cols)")
