# ========== WordOrderCaptchaView ==========
lines.append("")
lines.append("")
lines.append("class WordOrderCaptchaView(BaseCaptchaView):")
lines.append('    """语序点选验证码视图"""')
lines.append("    def __init__(self, parent, viewmodel, width=400, height=200):")
lines.append("        self.vm = viewmodel")
lines.append("        super().__init__(parent, viewmodel, width, height)")
lines.append("    def _build_ui(self):")
lines.append("        super()._build_ui()")
lines.append("        btn_frame = ttk.Frame(self.frame)")
lines.append("        btn_frame.pack(pady=5)")
lines.append("        ttk.Button(btn_frame, text=\"刷新\", command=self.reset).pack(side=tk.LEFT, padx=5)")
lines.append("        self.instruction_label = tk.Label(self.frame, text=\"\", font=('微软雅黑', 11), fg='#2196F3')")
lines.append("        self.instruction_label.pack(pady=2)")
lines.append("        self.canvas.bind('<Button-1>', self._on_click)")
lines.append("        self.draw()")
lines.append("    def draw(self):")
lines.append("        self.canvas.delete('all')")
lines.append("        data = self.vm.model.word_order_data")
lines.append("        if data is None:")
lines.append("            return")
lines.append("        state = self.vm.get_state()")
lines.append("        words = data.shuffled_words")
lines.append("        n = len(words)")
lines.append("        box_w = min(80, (self.width - 40) // n)")
lines.append("        box_h = 60")
lines.append("        start_x = (self.width - n * box_w) // 2")
lines.append("        start_y = 30")
lines.append("        for i, word in enumerate(words):")
lines.append("            x = start_x + i * box_w")
lines.append("            y = start_y")
lines.append("            if i in data.clicked_order:")
lines.append("                bg = '#4CAF50'")
lines.append("            else:")
lines.append("                bg = '#2196F3'")
lines.append("            self.canvas.create_rectangle(x+2, y+2, x+box_w-2, y+box_h-2, fill=bg, outline='white', width=2)")
lines.append("            self.canvas.create_text(x + box_w//2, y + box_h//2, text=word, font=('微软雅黑', 16, 'bold'), fill='white')")
lines.append("        if state == CaptchaState.SUCCESS:")
lines.append("            self.instruction_label.config(text='验证成功！', fg='#4CAF50')")
lines.append("        elif state == CaptchaState.FAILED:")
lines.append("            self.instruction_label.config(text='顺序错误，请重试', fg='#f44336')")
lines.append("        else:")
lines.append("            instruction = data.instruction")
lines.append("            correct = data.words[:len(data.clicked_order)+1]")
lines.append("            self.instruction_label.config(text=f\"{instruction} {' → '.join(correct)}\", fg='#2196F3')")
lines.append("    def _on_click(self, event):")
lines.append("        data = self.vm.model.word_order_data")
lines.append("        if data is None:")
lines.append("            return")
lines.append("        words = data.shuffled_words")
lines.append("        n = len(words)")
lines.append("        box_w = min(80, (self.width - 40) // n)")
lines.append("        start_x = (self.width - n * box_w) // 2")
lines.append("        start_y = 30")
lines.append("        for i in range(n):")
lines.append("            x = start_x + i * box_w")
lines.append("            y = start_y")
lines.append("            if x <= event.x <= x + box_w and y <= event.y <= y + 60:")
lines.append("                self.vm.click(i)")
lines.append("                break")
lines.append("    def reset(self):")
lines.append("        super().reset()")
lines.append("        self.instruction_label.config(text='', fg='#2196F3')")

