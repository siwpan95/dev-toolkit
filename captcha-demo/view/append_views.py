lines.append("            self.canvas.create_rectangle(x, y, x+size, y+size, fill=img['color'], outline='#ddd', width=1)")
lines.append("            cx, cy = x + size//2, y + size//2")
lines.append("            shape = img['shape']")
lines.append("            if shape == 'circle':")
lines.append("                self.canvas.create_oval(cx-20, cy-20, cx+20, cy+20, fill='white', outline='#333', width=2)")
