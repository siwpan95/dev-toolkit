lines.append("        self.draw()")
lines.append("    def draw(self):")
lines.append("        self.canvas.delete('all')")
lines.append("        data = self.vm.model.scratch_card_data")
lines.append("        if data is None:")
lines.append("            return")
lines.append("        cx, cy = self.width//2, self.height//2")
lines.append("        cw, ch = 200, 80")
lines.append("        x1, y1 = cx - cw//2, cy - ch//2")
lines.append("        x2, y2 = cx + cw//2, cy + ch//2")
lines.append("        # 底层：答案")
lines.append("        self.canvas.create_rectangle(x1, y1, x2, y2, fill='#FFF8E1', outline='#FFE082')")
lines.append("        self.canvas.create_text(cx, cy, text=data.answer, font=('Arial', 28, 'bold'), fill='#F57F17')")
lines.append("        # 涂层")
lines.append("        scratched = set()")
lines.append("        for sx, sy in data.scratched:")
lines.append("            for dx in range(-15, 16):")
lines.append("                for dy in range(-15, 16):")
lines.append("                    px, py = int(sx+dx), int(sy+dy)")
lines.append("                    if x1 <= px <= x2 and y1 <= py <= y2:")
lines.append("                        scratched.add((px, py))")
lines.append("        for px in range(int(x1), int(x2)+1):")
lines.append("            for py in range(int(y1), int(y2)+1):")
lines.append("                if (px, py) not in scratched:")
lines.append("                    self.canvas.create_rectangle(px, py, px+1, py+1, fill='#9E9E9E', outline='')")
lines.append("        self.canvas.create_rectangle(x1, y1, x2, y2, outline='#757575', width=2)")
lines.append("    def _on_press(self, event):")
lines.append("        self.vm.start_drag(event.x, event.y)")
lines.append("    def _on_drag(self, event):")
lines.append("        self.vm.drag(event.x, event.y)")
lines.append("    def _on_release(self, event):")
lines.append("        self.vm.end_drag()")
lines.append("    def _verify(self):")
lines.append("        user_input = self.entry.get().strip()")
lines.append("        if user_input:")
lines.append("            self.vm.verify(user_input)")
lines.append("            self.entry.delete(0, tk.END)")
lines.append("    def reset(self):")
lines.append("        super().reset()")
lines.append("        self.entry.delete(0, tk.END)")

