lines.append("        data.target_indices = []")
lines.append("        for i, animal in enumerate(selected[:9]):")
lines.append("            is_target = animal in animals[:3]")
lines.append("            if is_target:")
lines.append("                data.target_indices.append(i)")
lines.append("            data.grids.append({'index': i, 'animal': animal, 'is_target': is_target})")
lines.append("        data.clicked_indices = [)")
lines.append("        self.nine_grid_data = data")
lines.append("        self.state = CaptchaState.IDLE")
lines.append("        return data")
lines.append("    def verify(self, clicked_index: int) -> 'CaptchaResult':")
lines.append("        if not hasattr(self, 'nine_grid_data') or self.nine_grid_data is None:")
lines.append('            return CaptchaResult(success=False, message="验证码未生成")')
lines.append("        data = self.nine_grid_data")
lines.append("        if clicked_index in data.clicked_indices:")
lines.append("            return self.result")
lines.append("        data.clicked_indices.append(clicked_index)")
lines.append("        self.result.attempts += 1")
lines.append("        all_clicked = all(idx in data.clicked_indices for idx in data.target_indices)")
lines.append("        if all_clicked:")
lines.append('            self.state = CaptchaState.SUCCESS')
lines.append('            self.result.success = True')
lines.append('            self.result.message = "验证成功"')
lines.append('            self.result.score = 1.0')
lines.append("        else:")
lines.append('            remaining = [idx for idx in data.target_indices if idx not in data.clicked_indices]')
lines.append('            self.result.message = f"已选 {len(data.clicked_indices)}，还需选择 {len(remaining)} 个"')
lines.append("        return self.result")

