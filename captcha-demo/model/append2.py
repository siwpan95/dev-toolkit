# ========== WordOrderCaptchaModel ==========
lines.append("")
lines.append("# ========== 新增验证码 Model ==========")
lines.append("")
lines.append("class WordOrderCaptchaModel(CaptchaModel):")
lines.append('    """语序点选验证码模型"""')
lines.append("    def __init__(self):")
lines.append("        super().__init__(CaptchaType.WORD_ORDER)")
lines.append("        self.word_pool = [")
lines.append('            ["我", "爱", "中国", "编程"],')
lines.append('            ["今天", "天气", "真", "好"],')
lines.append('            ["人机", "验证", "很", "有趣"],')
lines.append('            ["Python", "是", "一门", "编程语言"],')
lines.append('            ["验证码", "可以", "防止", "机器人"],')
lines.append("        ]")
lines.append("    def generate(self, config: CaptchaConfig):")
lines.append("        data = WordOrderCaptchaData()")
lines.append("        sentence = random.choice(self.word_pool)")
lines.append("        data.words = sentence.copy()")
lines.append("        data.target_count = len(sentence)")
lines.append("        data.shuffled_words = sentence.copy()")
lines.append("        random.shuffle(data.shuffled_words)")
lines.append("        data.clicked_order = []")
lines.append("        self.word_order_data = data")
lines.append("        self.state = CaptchaState.IDLE")
lines.append("        return data")
lines.append("    def verify(self, clicked_index: int) -> 'CaptchaResult':")
lines.append("        if not hasattr(self, 'word_order_data') or self.word_order_data is None:")
lines.append('            return CaptchaResult(success=False, message="验证码未生成")')
lines.append("        data = self.word_order_data")
lines.append("        data.clicked_order.append(clicked_index)")
lines.append("        self.result.attempts += 1")
lines.append("        expected_word = data.words[len(data.clicked_order) - 1]")
lines.append("        actual_word = data.shuffled_words[clicked_index]")
lines.append("        if actual_word != expected_word:")
lines.append('            self.state = CaptchaState.FAILED')
lines.append('            self.result.success = False')
lines.append('            self.result.message = f"顺序错误，应是「{expected_word}」"')
lines.append("            data.clicked_order = []")
lines.append("            return self.result")
lines.append("        if len(data.clicked_order) >= data.target_count:")
lines.append('            self.state = CaptchaState.SUCCESS')
lines.append('            self.result.success = True')
lines.append('            self.result.message = "验证成功"')
lines.append('            self.result.score = 1.0')
lines.append("        else:")
lines.append('            next_word = data.words[len(data.clicked_order)]')
lines.append('            self.result.message = f"正确！请继续点击「{next_word}」"')
lines.append("        return self.result")

