// ===================== 构建均衡题库 =====================
function build() {
    const questions = [];
    const counts = {}; FUNC.forEach(f => counts[f] = 0);

    // 展开所有题（按 correct func 分组）
    const pools = {};
    FUNC.forEach(f => { pools[f] = []; });

    FUNC.forEach(f => {
        (STEMS[f] || []).forEach((text, i) => {
            pools[f].push({ text, correct: f, idx: i });
        });
    });

    // 所有题混合（按功能交替排列，使题库顺序多样化）
    const all = [];
    for (let i = 0; i < 16; i++) {
        FUNC.forEach(f => {
            if (pools[f][i]) all.push(pools[f][i]);
        });
    }

    // 为每道题分配 3 个干扰项，贪心保证全局均衡
    all.forEach((stem, qIdx) => {
        const used = new Set([stem.correct]);
        const dists = [];

        while (dists.length < 3) {
            // 选当前计数最低且未使用的功能
            let best = null, bestCnt = Infinity;
            FUNC.forEach(f => {
                if (!used.has(f) && counts[f] < bestCnt) {
                    best = f; bestCnt = counts[f];
                }
            });
            if (best === null) { best = FUNC.find(f => !used.has(f)); }
            if (best === null) break;
            dists.push(best);
            used.add(best);
        }

        // 构建 4 个选项（correct + 3 dists），洗牌
        const funcs = [stem.correct, ...dists];
        // 稳定洗牌（用 qIdx 做种子）
        for (let i = funcs.length - 1; i > 0; i--) {
            const j = (qIdx * 31 + i * 17) % (i + 1);
            [funcs[i], funcs[j]] = [funcs[j], funcs[i]];
        }

        const options = funcs.map(f => {
            const txtPool = OPTS[f] || [];
            const txtIdx = (stem.idx * 8 + qIdx) % txtPool.length;
            return { text: txtPool[txtIdx], func: f };
        });

        // 累加计数
        options.forEach(o => { counts[o.func]++; });

        questions.push({ text: stem.text, options });
    });

    return questions;
}

